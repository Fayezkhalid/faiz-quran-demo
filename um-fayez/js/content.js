export function partOfDay(d = new Date(), times) {
  const t = d.getTime();
  if (times) {
    if (t < times.fajr) return 'night';
    if (t < times.sunrise) return 'fajr';
    if (t < times.dhuhr - 30 * 60000) return 'morning';
    if (t < times.asr) return 'noon';
    if (t < times.isha + 60 * 60000) return 'evening';
    return 'night';
  }
  const h = d.getHours();
  if (h < 4) return 'night';
  if (h < 6) return 'fajr';
  if (h < 12) return 'morning';
  if (h < 16) return 'noon';
  if (h < 21) return 'evening';
  return 'night';
}

export const rand = (arr) => arr[Math.floor(Math.random() * arr.length)];

// دعاء مختلف كل مرة: نتجنّب تكرار آخر دعاء ظهر
export function nextDua() {
  let last = -1;
  try { last = +localStorage.getItem('sakina.lastDua'); } catch {}
  let i;
  do { i = Math.floor(Math.random() * DUAS.length); } while (i === last && DUAS.length > 1);
  try { localStorage.setItem('sakina.lastDua', i); } catch {}
  return DUAS[i];
}

